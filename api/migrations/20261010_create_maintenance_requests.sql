BEGIN;

CREATE TABLE public.maintenance_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT NOT NULL,
    photo_path TEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    resolution_notes TEXT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT maintenance_requests_booking_id_fkey
        FOREIGN KEY (booking_id)
        REFERENCES public.bookings (booking_id)
        ON DELETE RESTRICT,
    CONSTRAINT maintenance_requests_category_not_blank
        CHECK (btrim(category) <> ''),
    CONSTRAINT maintenance_requests_description_not_blank
        CHECK (btrim(description) <> ''),
    CONSTRAINT maintenance_requests_status_check
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'REJECTED'))
);

CREATE INDEX maintenance_requests_booking_id_idx
    ON public.maintenance_requests (booking_id);

CREATE INDEX maintenance_requests_status_idx
    ON public.maintenance_requests (status);

CREATE INDEX maintenance_requests_submitted_at_idx
    ON public.maintenance_requests (submitted_at);

CREATE FUNCTION public.maintenance_requests_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER maintenance_requests_updated_at_trigger
BEFORE UPDATE ON public.maintenance_requests
FOR EACH ROW
EXECUTE FUNCTION public.maintenance_requests_set_updated_at();

COMMIT;
